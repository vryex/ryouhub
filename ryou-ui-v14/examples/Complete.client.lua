local UI = require(script.Parent:WaitForChild("RyouUI"))
local window = UI:CreateWindow({ Title = "Mesa de trabajo", Subtitle = "Created by Ryou" })
local workspace = window:Group({ Title = "PANEL" })
local home = workspace:Tab({ Title = "Inicio", Icon = "home" })
local settings = workspace:Tab({ Title = "Preferencias", Icon = "sliders" })

home:Section({ Title = "Sesión" })
local status = home:Paragraph({ Title = "Estado", Desc = "Listo para editar.", Icon = "info" })
home:Button({ Title = "Preferencias", Action = "Abrir", Callback = function() settings:Select() end })
settings:Section({ Title = "Perfil visual" })
settings:Toggle({ Title = "Tema claro", Value = false, Callback = function(enabled)
    window:SetTheme(enabled and "Light" or "Dark")
end })
settings:Slider({ Title = "Intensidad de muestra", Min = 0, Max = 50, Step = 5, Default = 20,
    Callback = function(value) status:SetDesc("Intensidad: " .. value) end })
settings:Input({ Title = "Nombre del espacio", Placeholder = "Mesa de trabajo", Callback = function(value)
    window:SetTitle(value ~= "" and value or "Mesa de trabajo")
end })
settings:Dropdown({ Title = "Familias", Values = { "Editorial", "Técnica", "Archivo", "Boceto" },
    Multi = true, Default = { "Técnica" }, Callback = function(values)
        status:SetDesc(#values > 0 and table.concat(values, " / ") or "Sin familias")
    end })
settings:Colorpicker({ Title = "Acento", Value = Color3.fromRGB(132, 241, 198), Callback = function(value)
    window:SetTheme({ Name = window:GetTheme(), Accent = value })
end })
