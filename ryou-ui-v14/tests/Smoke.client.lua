-- Colocar en StarterPlayerScripts junto a RyouUI (ModuleScript) para probar en Play.
local UI = require(script.Parent:WaitForChild("RyouUI"))
assert(UI.Version == "14.0.0")
assert(table.find(UI:GetIcons(), "ryou"))
local w = UI:CreateWindow({ Open = false, Motion = "Off", Size = UDim2.fromOffset(320, 240) })
local t = w:Group({ Title = "Pruebas" }):Tab({ Title = "Inicio", Icon = "home" })
assert(w:SelectTab(1) == t)
t:Section({ Title = "Controles" })
local button = t:Button({ Title = "Probar" })
button:Lock():Unlock()
local calls = 0
local toggle = t:Toggle({ Value = false, Callback = function(value)
    assert(value == true)
    calls += 1
end })
toggle:SetValue(true):SetValue(true)
assert(toggle:Get() and calls == 1)
local slider = t:Slider({ Value = { Min = 10, Max = 1, Default = 4 }, Step = 2 })
assert(slider:Get() == 5)
slider:Set(10)
assert(slider:Get() == 10)
local input = t:Input({ Default = "Ryou" })
assert(input:Get() == "Ryou")
local dropdown = t:Dropdown({ Values = { "A", "B", "A" }, Multi = true, Value = { "B", "A" } })
dropdown:Open():Close()
assert(table.concat(dropdown:Get()) == "BA")
dropdown:Refresh({ "B", "C" })
assert(table.concat(dropdown:Get()) == "BA")
local single = t:Dropdown({ Values = { 0, 1 }, Value = 0 })
assert(single:Get() == 0)
local color = t:Colorpicker({ Default = Color3.fromHex("84F1C6") })
assert(color:Get() == Color3.fromHex("84F1C6"))
local paragraph = t:Paragraph({ Title = "Estado" })
paragraph:Set("Correcto"):Hide():Show()
w:SetTheme("Blanco")
assert(w:GetTheme() == "Light")
local opened, closed, destroyed = 0, 0, 0
w:OnOpen(function() opened += 1 end):OnClose(function() closed += 1 end)
w:OnDestroy(function() destroyed += 1 end)
w:Open():Close():Open()
assert(w.Opened and opened == 2 and closed == 1)
local notice = w:Notify({ Title = "Prueba", Type = "success" })
notice:Dismiss()
button:Destroy()
w:SetSize(Vector2.new(640, 360)):SetToTheCenter()
assert(w:GetSize() == Vector2.new(640, 360))
local nextWindow = UI:CreateWindow({ Open = false, Motion = "Off" })
assert(destroyed == 1 and w.Destroyed)
nextWindow:Destroy()
assert(UI.Window == nil)
print("Ryou UI V14: smoke OK")
