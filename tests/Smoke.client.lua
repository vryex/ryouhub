local storage = game:GetService("ReplicatedStorage")
local UI = require(storage:WaitForChild("RyouUI"))

local w = UI:CreateWindow({Title = "Prueba", Motion = "off", Opened = false})
assert(not w.Opened and w.OpenButton.Visible)
local opened, closed, destroyed = 0, 0, 0
w:OnOpen(function() opened += 1 end)
w:OnClose(function() closed += 1 end)
w:OnDestroy(function() destroyed += 1 end)
w:Open():Open()
assert(opened == 1 and w.Opened and not w.OpenButton.Visible)

local home = w:Section("Pruebas"):Tab({Title = "Inicio", Icon = "home"})
local second = w:Tab("Otra")
assert(w:SelectTab("Otra") == second)
assert(w:SelectTab(1) == home)
home:Section("Controles")
local paragraph = home:Paragraph({Title = "Texto", Gothic = true})
paragraph:SetDesc("Actualizado"):Hide():Show()
assert(paragraph.Desc == "Actualizado")
home:Button({Title = "Botón"}):Lock():Unlock()
local footer = home:FooterButton({Title = "Aplicar", Locked = true})
footer:Unlock():SetTitle("Guardar")
footer:Destroy()
local callbackCount = 0
local toggle = home:Toggle({Value = true, Callback = function(v)
    assert(v == false)
    callbackCount += 1
end})
toggle:Set(false):Set(false):Set(true, true)
assert(toggle:Get() and callbackCount == 1)
local input = home:Input({Default = "Inicial", Locked = true})
assert(not input.Interactive.TextEditable)
input:Unlock():Set("Nuevo")
assert(input:Get() == "Nuevo" and input.Interactive.TextEditable)
local slider = home:Slider({Value = {Min = 1, Max = 10, Default = 4}, Step = 3})
assert(slider:Get() == 4)
assert(slider:Set(100, true):Get() == 10)
local inputMulti = {"A"}
local multi = home:Dropdown({Values = {"A","B"}, Multi = true, Default = inputMulti})
inputMulti[1] = "Z"
assert(multi:Get()[1] == "A")
multi:Open():Open()
task.wait()
assert(multi.InlineDropdown.Visible)
local single = home:Dropdown({Values = {"X","Y"}, Default = "X"})
single:Open()
task.wait()
assert(single.InlineDropdown.Visible and not multi.InlineDropdown.Visible)
single:Refresh({"X","Y","Z"}):Set("Z",true):Close(true)
assert(single:Get() == "Z")
local color = home:Colorpicker({Default = Color3.fromRGB(100, 100, 100)})
local newColor = Color3.fromRGB(150, 234, 201)
assert(color:Set(newColor, true):Get() == newColor)
color:Open()
task.wait()
assert(w._popupLayer ~= nil)
color:Lock()
assert(w._popupLayer == nil)
color:Destroy()
assert(not table.find(home.Elements,color))

w:SetTheme("White",true):SetMotion("reduced"):SetMotion("off"):SetSize(UDim2.fromOffset(400,330))
assert(w:GetTheme() == "Blanco" and w:GetMotion() == "off" and w:GetSize() == Vector2.new(400,330))
local notice = w:Notify({Type = "success", Title = "Prueba de aviso"})
assert(notice)
notice.Close()
w:Close():Close()
assert(closed == 1 and w.OpenButton.Visible)
local replacement = UI:CreateWindow({Title = "Recreación", Motion = "off"})
assert(w.Destroyed and destroyed == 1 and w.ScreenGui.Parent == nil)
replacement:Destroy()
assert(UI.Window == nil)
print("Ryou UI V14 smoke OK")
